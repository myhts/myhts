def double_road(d, dashed=False):
    dash = ' stroke-dasharray="9 7"' if dashed else ""
    return (
        f'<path d="{d}" fill="none" stroke="#1f1a14" stroke-width="11"{dash}/>'
        f'<path d="{d}" fill="none" stroke="#f1e7d0" stroke-width="7.8"/>'
    )


