#!/usr/bin/env python3
"""Draws the profile page's pictures as HTML pages in build/, and build/sizes.tsv for render.sh.

Every picture is drawn in code (HTML, CSS and inline SVG) in the colours and type of the Lombard theme. None is
generated by an image model. The fonts are loaded from Google Fonts when a page is rendered.

To change the trade card or the plan of the works, edit the text below, then run:

    python3 build.py && bash render.sh
"""
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent
BUILD = ROOT / "build"
BUILD.mkdir(exist_ok=True)
PAGES = []

FONTS = (
    '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=IM+Fell+English+SC'
    "&amp;family=IM+Fell+English:ital@0;1&amp;family=Libre+Caslon+Text:ital,wght@0,400;0,700;1,400"
    '&amp;display=swap">'
)

CSS = """
*{box-sizing:border-box}
html,body{margin:0;background:transparent}
body{font-family:'Libre Caslon Text',Georgia,serif;color:#1f1a14;-webkit-font-smoothing:antialiased;position:relative}
p,h1,h2,h3{margin:0;font-weight:400}
.paper{background-color:#f1e7d0;background-image:
  radial-gradient(ellipse at 22% 14%,rgba(255,250,235,.55),transparent 55%),
  radial-gradient(ellipse at 82% 88%,rgba(190,160,105,.20),transparent 50%),
  repeating-linear-gradient(0deg,rgba(120,95,50,.075) 0,rgba(120,95,50,.075) 1px,transparent 1px,transparent 5px);
  box-shadow:inset 0 0 70px rgba(150,120,70,.42),inset 0 0 5px rgba(110,85,40,.55)}
.fell{font-family:'IM Fell English',serif}
.sc{font-family:'IM Fell English SC',serif;letter-spacing:.07em}
.it{font-style:italic}
.soft{color:#685b48}
.pressed{text-shadow:0 1px 0 rgba(255,255,255,.4),0 0 1px rgba(31,26,20,.45)}
.abs{position:absolute}
"""


def page(name, w, h, body, scale=2, quality="84"):
    """Writes one picture's page. quality is the JPEG quality, or "png" to keep the transparent ground."""
    doc = (
        f'<!doctype html><html lang="en"><head><meta charset="utf-8"><title>{name}</title>{FONTS}'
        f"<style>{CSS}</style></head>"
        f'<body style="width:{w}px;height:{h}px;overflow:hidden">{body}</body></html>'
    )
    (BUILD / f"{name}.html").write_text(doc, encoding="utf-8")
    PAGES.append((name, w, h, scale, quality))


def fleuron_rule(width, colour, extra=""):
    """A printer's double rule, tapering, with a flower in the middle."""
    mid = width / 2
    gap = 34
    return (
        f'<svg width="{width}" height="28" viewBox="0 0 {width} 28" style="display:block;{extra}">'
        f'<g fill="{colour}">'
        f'<path d="M0 13.2 L{mid - gap} 12 L{mid - gap} 14.6 L0 13.8Z"/>'
        f'<path d="M{width} 13.2 L{mid + gap} 12 L{mid + gap} 14.6 L{width} 13.8Z"/>'
        f'<rect x="{width * 0.12}" y="17.6" width="{mid - gap - width * 0.12}" height="0.9"/>'
        f'<rect x="{mid + gap}" y="17.6" width="{mid - gap - width * 0.12}" height="0.9"/>'
        f'<path d="M{mid} 3 L{mid + 7} 14 L{mid} 25 L{mid - 7} 14Z"/>'
        f'<circle cx="{mid - 17}" cy="14" r="3.2"/><circle cx="{mid + 17}" cy="14" r="3.2"/>'
        f'<circle cx="{mid - 27}" cy="14" r="1.6"/><circle cx="{mid + 27}" cy="14" r="1.6"/>'
        f"</g></svg>"
    )


def compass(cx, cy, r):
    """An engraver's compass rose, as SVG elements for an existing <svg>."""
    out = [
        f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="none" stroke="#1f1a14" stroke-width="1.2"/>',
        f'<circle cx="{cx}" cy="{cy}" r="{r - 5}" fill="none" stroke="#1f1a14" stroke-width=".6"/>',
    ]
    for k in range(8):
        a = math.radians(k * 45)
        length = r - 8 if k % 2 == 0 else (r - 8) * 0.55
        tip = (cx + length * math.sin(a), cy - length * math.cos(a))
        w = 6 if k % 2 == 0 else 4
        left = (cx + w * math.sin(a - math.pi / 2), cy - w * math.cos(a - math.pi / 2))
        right = (cx + w * math.sin(a + math.pi / 2), cy - w * math.cos(a + math.pi / 2))
        out.append(
            f'<path d="M{tip[0]:.1f} {tip[1]:.1f} L{left[0]:.1f} {left[1]:.1f} L{cx} {cy}Z" fill="#1f1a14"/>'
            f'<path d="M{tip[0]:.1f} {tip[1]:.1f} L{right[0]:.1f} {right[1]:.1f} L{cx} {cy}Z" fill="#f1e7d0" '
            f'stroke="#1f1a14" stroke-width=".7"/>'
        )
    out.append(
        f'<text x="{cx}" y="{cy - r - 7}" text-anchor="middle" font-family="IM Fell English SC, serif" '
        f'font-size="15" fill="#1f1a14">N</text>'
    )
    return "".join(out)

